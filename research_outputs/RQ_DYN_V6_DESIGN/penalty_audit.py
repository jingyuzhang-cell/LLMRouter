import json, re, sys, glob, os

def audit(slot_value, detail):
    """detail: [(主体,金额万)]"""
    total=sum(a for _,a in detail)
    nums=re.findall(r'(\d[\d,，]*)\s*万', str(slot_value))
    claimed=[int(n.replace(",","").replace("，","")) for n in nums] if nums else []
    ok= (total in claimed) if claimed else False
    return dict(computed=total, claimed=claimed, match=ok, n_items=len(detail))

