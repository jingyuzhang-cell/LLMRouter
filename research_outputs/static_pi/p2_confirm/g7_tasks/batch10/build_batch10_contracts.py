def strip_with_map(raw):
    out, idx = [], []
    for i, ch in enumerate(raw):
        if not ch.isspace(): out.append(ch); idx.append(i)
    return ''.join(out), idx

def strip_pageno(t):
    return re.sub(r'\n\s*\d+\s*(?=\n|$)', '', t)

docs_cache = {}
def load_doc(fname):
    if fname not in docs_cache:
        raw = strip_pageno((HERE / 'raw' / fname).read_text(errors='ignore'))
        st, idx = strip_with_map(raw)
        for wrong, right, why in CORRECTIONS.get(fname, []):
            pos = st.find(wrong)
            assert pos >= 0, f'correction target missing: {wrong}'
            st = st[:pos] + right + st[pos + len(wrong):]
            CORR_LOG.append(dict(file=fname, text_layer=wrong, printed=right, reason=why))
        docs_cache[fname] = dict(raw=raw, stripped=st, idx=idx)
    return docs_cache[fname]

