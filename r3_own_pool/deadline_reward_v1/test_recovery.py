"""M4 acceptance tests — static recovery arms + T3a/T3b equivalence.

Production references are generated BY PRODUCTION CODE driven through
stub executors (read-only imports, zero real calls):
  - NONE / LOCAL: evaluator._evaluate (recovery=True mirrors the D-arm
    LOCAL machinery) with predictor_v3.V3Executor.
  - FULL: the SAME production path netbenefit_runner uses for the E arm —
    base _evaluate(recovery=False), then netbenefit_runner.recovery_plans
    + grouped _evaluate replays (frozen E-arm MATCHED semantics; NOT
    JointEvaluator's all-swap FULL).

T3a: per-task (node, kind, model, cached, injected, uid) sequences equal.
T3b: global order + physical request/token accounting equal.
Plus the operator's eight boundary tests. Socket blocked; zero real calls.

Run: python3 -m deadline_reward_v1.test_recovery  (any CWD)
"""
