HERE = Path(__file__).resolve().parent
PRIORS = json.loads((HERE / 'PRIORS_STUB_V1.json').read_text())
RUNS_DIR = HERE / 'evidence' / 'm4_runs'
NODES_MODELS = {'e1': 'large', 'e2': 'large', 'r': 'medium', 'v': 'coder'}

GOOD_E1 = '{"facts": [{"value": 1.5, "evidence": "a"}]}'
GOOD_E2 = '{"facts": [{"value": 2.5, "evidence": "b"}]}'
GOOD_R = '{"expression": "v0+v1"}'
GOOD_V = '{"value": 4.0}'
BASE = {('e1', 'plain'): GOOD_E1, ('e2', 'plain'): GOOD_E2,
        ('r', 'plain'): GOOD_R, ('v', 'plain'): GOOD_V,
        ('e1', 'fb'): GOOD_E1, ('e2', 'fb'): GOOD_E2,
        ('r', 'fbd'): GOOD_R, ('r', 'esc'): GOOD_R,
        ('v', 'fbd'): GOOD_V, ('v', 'esc'): GOOD_V}
FAULTS = {
    'm1t1': ('e1', '{"facts": []}'),
    'm1t2': ('r', '###SYNTHETIC UNPARSEABLE r-output###'),
    'm1t3': ('v', '{"value": null}'),
    'm1t4': ('e1', '{"facts": []}'),
}
# production faults are ONE node per task (eval_config single-fault panel);
# the same-model-retry probe below uses its own two-task single-fault panel.


def make_tasks():
    def t(i, a, b):
        return dict(uid=f'm1t{i}', question=f'What is {a} + {b}?',
                    derivation=f'{a}+{b}', answer=a + b,
                    ctx_table=f'TABLE: | val | {a} |',
                    ctx_text=f'PASSAGES: value is {b}')
    return [t(0, 1.5, 2.5), t(1, 3.0, 4.0), t(2, 2.0, 6.0),
            t(3, 5.0, 1.0), t(4, 2.0, 2.0)]


@contextlib.contextmanager
def no_socket():
    def _raise(*_a, **_k):
        raise AssertionError('network access attempted (Z2)')
    saved = _socket_mod.socket
    _socket_mod.socket = _raise
    try:
        yield
    finally:
        _socket_mod.socket = saved


def production_reference(arm, tasks):
    """Independent reference via the PRODUCTION executor the net-benefit
    campaign actually ran: MeteredExecutor (fault-after-metering, cache
    identity scoped by node position — replay identities sit under the
    'replay' key slot, so replays are NEVER cache-substituted and faults
    keyed by node name cannot re-fire inside them) driven by _evaluate and,
    for FULL, netbenefit_runner.recovery_plans + grouped replays. A stub
    dispatch returns the SAME scripted answers my engine's server returns;
    a real Budget meters physical spend. Zero real model calls."""
    import tempfile
    led = fp.Ledger()
    tmp = tempfile.TemporaryDirectory()

    def dispatch(model, prompt):
        # Route by the production templates' distinctive markers (order
        # matters: VPROMPT also contains 'arithmetic', sprompt also
        # contains 'extracted').
        if 'verifying' in prompt:
            ans = GOOD_V
        elif 'Choose the arithmetic' in prompt:
            ans = GOOD_R
        elif 'extract' in prompt:
            ans = GOOD_E1 if 'TABLE' in prompt else GOOD_E2
        else:
            raise AssertionError('unroutable prompt: ' + prompt[:80])
        return dict(status='delivered', answer=ans,
                    usage=dict(prompt_tokens=60, completion_tokens=40,
                               total_tokens=100))

    budget = Budget(Path(tmp.name), dict(
        new_request_attempts=100000, new_total_tokens=10 ** 9,
        request_token_reservation=8192, max_output_tokens=512,
        wall_seconds=3600, logical_calls_per_task_config_state=1000))
    ex = MeteredExecutor(Path(tmp.name), budget, dispatch, lambda m: None,
                         dict(medium='medium', large='large', coder='coder'))
    collected: list = []

    def arm_eval(config, subset, faults, recovery, label, cell):
        ex.begin_cell(cell, config['id'])   # JointEvaluator-style usage
        for uid, (node, failing) in faults.items():
            ex.set_fault(uid, node, NODES_MODELS[node], failing, {}, 0.0)
        rows = _evaluate(config, ex, led, subset, faults, label=label,
                         recovery=recovery)
        collected.extend(dict(r) for r in ex.events)
        return rows

    config = dict(id='m4ref', X=dict(NODES_MODELS))
    rows = arm_eval(config, tasks, FAULTS, arm == 'LOCAL', 'm4', 'clean')
    if arm == 'FULL':
        plans = recovery_plans(rows, ex, led, tasks)
        groups = {}
        for t in tasks:
            if t['uid'] in plans:
                key = tuple(sorted(plans[t['uid']].items()))
                groups.setdefault(key, []).append(t)
        for key, group in sorted(groups.items()):
            retry_config = copy.deepcopy(config)
            retry_config['id'] = 'm4ref:replay'
            retry_config['X'] = {**NODES_MODELS, **dict(key)}
            arm_eval(retry_config, group, FAULTS, False, 'm4:replay',
                     'replay')
    kinds = {'plain', 'fb', 'fbd', 'esc'}
    seq = []
    for rec in collected:
        parts = rec['key'].split(':')
        uid = parts[-1]
        node = parts[-3 if parts[-2] in kinds else -2]
        kind = parts[-2] if parts[-2] in kinds else 'plain'
        seq.append((node, kind, rec['model'],
                    bool(rec.get('alias_of')),
                    bool(rec.get('answer_replaced_after_call'))
                    or bool(rec['response'].get('injected_fault')), uid))
    tmp.cleanup()
    return seq, budget.attempts, budget.actual_tokens


def run_mine(dirname, arm, tasks, *, mutate_ctx=None, none_override=None):
    answers = dict(BASE)
    if none_override is not None:
        answers[none_override] = None
    server = StubModelServer(answers, PRIORS, seed='m4')
    for uid, (node, failing) in FAULTS.items():
        server.set_fault(uid, node, NODES_MODELS[node], failing)
    clock = InjectedClock()
    engine = StubEngine(RUNS_DIR / dirname, server, clock, seed='m4',
                        profile_key='v3_compat')
    state = SchedulerState(clock,
                           task_deadlines={t['uid']: 100.0 for t in tasks},
                           token_allocation=100000.0)
    state.attach(engine)
    if mutate_ctx is not None:
        # ctx-mutation probe: run planned stage, then mutate and re-call
        engine.start_panel(tasks, NODES_MODELS)
        engine.run_jobs('A', engine.planned_jobs(tasks, NODES_MODELS,
                                                 ('e1',)))
        tasks[0]['ctx_table'] = mutate_ctx
        try:
            engine.run_jobs('A', engine.planned_jobs(tasks, NODES_MODELS,
                                                     ('e2',)))
            ctx_raised = False
        except ValueError:
            ctx_raised = True
        return dict(engine=engine, state=state, server=server,
                    ctx_raised=ctx_raised, events=[], tasks=tasks)
    if none_override is not None:
        try:
            rec.run_arm(engine, state, tasks, NODES_MODELS, 'NONE')
            none_raised = False
        except ValueError:
            none_raised = True
        return dict(engine=engine, state=state, server=server,
                    none_raised=none_raised, events=[], tasks=tasks)
    rec.run_arm(engine, state, tasks, NODES_MODELS, arm)
    events, torn = load_ledger(RUNS_DIR / dirname / 'TASK_LEDGER.jsonl')
    return dict(engine=engine, state=state, server=server, events=events,
                torn=torn, tasks=tasks, clock=clock)


def mine_seq(events):
    return [(c['node'], c['kind'], c['model'], c['cached'], c['injected'],
             c['task']) for c in events if c['event'] == 'call']


def main():
    import shutil
    shutil.rmtree(RUNS_DIR, ignore_errors=True)
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    checks = {}
    detail = {}
    tasks = make_tasks()

    for arm in ('NONE', 'LOCAL', 'FULL'):
        ref_seq, ref_phys_calls, ref_phys_tokens = \
            production_reference(arm, tasks)
        run = run_mine(f'arm_{arm}', arm, tasks)
        seq = mine_seq(run['events'])
        per_task_ok = all(
            [s for s in seq if s[5] == u] == [s for s in ref_seq if s[5] == u]
            for u in {t['uid'] for t in tasks})
        eng = run['engine']
        sess = next(e for e in run['events']
                    if e['event'] == 'session_summary')
        checks[f't3a_{arm}_per_task'] = per_task_ok
        checks[f't3b_{arm}_global_order'] = seq == ref_seq
        checks[f't3b_{arm}_physical_requests'] = (
            sess['requests'] == ref_phys_calls)
        checks[f't3b_{arm}_physical_tokens'] = (
            sess['tokens_total'] == ref_phys_tokens)
        checks[f't3b_{arm}_not_torn'] = not run['torn']
        detail[f'{arm}_reference'] = dict(
            source='evaluator._evaluate'
                   + (' + netbenefit_runner.recovery_plans (E-arm)'
                      if arm == 'FULL' else ''),
            calls=len(ref_seq), physical=ref_phys_calls,
            physical_tokens=ref_phys_tokens)

    # ---- T3a literal single-task panels (M4 acceptance round) ----------
    # One-task panel per arm: the production reference and the engine run
    # the SAME faulted task alone; sequences and physical accounting must
    # match bitwise (no batching to lean on).
    for arm in ('NONE', 'LOCAL', 'FULL'):
        single = [make_tasks()[1]]  # the e1-faulted task, alone
        ref1, ref1_phys, ref1_tok = production_reference(arm, single)
        run1 = run_mine(f'single_{arm}', arm, single)
        seq1 = mine_seq(run1['events'])
        sess1 = next(e for e in run1['events']
                     if e['event'] == 'session_summary')
        checks[f't3a_single_panel_{arm}'] = (
            seq1 == ref1
            and sess1['requests'] == ref1_phys
            and sess1['tokens_total'] == ref1_tok
            and len(seq1) == len(ref1))

    # ---- boundary tests (operator instruction §四) -----------------------
    # 1. task static context is frozen: mutation mid-episode is an error
    run = run_mine('ctx_freeze', 'NONE', make_tasks(),
                   mutate_ctx='TABLE: MUTATED')
    checks['b1_ctx_mutation_rejected'] = run['ctx_raised'] is True

    # 1b. judge: R=[] must not reuse a DONE cache under ctx drift
    from deadline_reward_v1 import dag_closure as dc
    probe_tasks = make_tasks()
    ctx = dc.ctx_signatures(probe_tasks[0])
    other = dc.ctx_signatures(dict(probe_tasks[0], ctx_table='TABLE X'))
    run_j = run_mine('judge_drift', 'NONE', probe_tasks)
    jst = run_j['state'].tasks['m1t0']
    jd = dc.evaluate_plan(
        node_status={n: DONE for n in dc.NODES},
        node_model=dict(NODES_MODELS),
        exec_identity={n: (NODES_MODELS[n], dc.input_signature(
            'm1t0', n, ctx, jst.answers)) for n in dc.NODES},
        R=[], pi={}, uid='m1t0', current_ctx_sha=other,
        parent_answers=jst.answers)
    checks['b1b_r_empty_no_stale_reuse'] = (
        not jd.legal and jd.invalidated == ('e1', 'r', 'v')
        and 'input_identity_changed:e1' in jd.reasons)

    # 2. explicit None answer override is an ERROR (no silent fallback)
    run = run_mine('none_override', 'NONE', make_tasks(),
                   none_override=('m1t0', 'e1', 'plain'))
    checks['b2_none_override_raises'] = run['none_raised'] is True

    # 3. FAILED same-model retry is a REAL new attempt with recorded cost.
    # Dedicated two-task panel (production: one fault per task): planned
    # e1=medium; both tasks' e1 faulted @medium; memory rule gives the
    # SECOND-detected task fb@medium — the SAME model as the failed call,
    # so the fault re-fires: a new attempt (attempt=2, injected, usage
    # recorded), never a zero-cost cache hit.
    probe_tasks = [dict(make_tasks()[1], uid='p0'),
                   dict(make_tasks()[2], uid='p1')]
    probe_models = {'e1': 'medium', 'e2': 'large', 'r': 'medium',
                    'v': 'coder'}
    server_p = StubModelServer(dict(BASE), PRIORS, seed='m4p')
    for u in ('p0', 'p1'):
        server_p.set_fault(u, 'e1', 'medium', '{"facts": []}')
    eng_p = StubEngine(RUNS_DIR / 'retry_probe', server_p, InjectedClock(),
                       seed='m4p', profile_key='v3_compat')
    st_p = SchedulerState(InjectedClock(),
                          task_deadlines={t['uid']: 100.0
                                          for t in probe_tasks},
                          token_allocation=100000.0)
    st_p.attach(eng_p)
    rec.run_arm(eng_p, st_p, probe_tasks, probe_models, 'LOCAL')
    ev_p, _ = load_ledger(RUNS_DIR / 'retry_probe' / 'TASK_LEDGER.jsonl')
    p1_e1 = [c for c in ev_p if c['event'] == 'call' and c['task'] == 'p1'
             and c['node'] == 'e1']
    obs_p1 = [o['code'] for o in st_p.task_view('p1')['observations']]
    checks['b3_failed_same_model_retry'] = (
        len(p1_e1) == 2
        and p1_e1[0]['model'] == p1_e1[1]['model'] == 'medium'
        and p1_e1[0]['kind'] == 'plain' and p1_e1[0]['injected']
        and p1_e1[1]['kind'] == 'fb' and p1_e1[1]['injected']
        and not p1_e1[1]['cached'] and p1_e1[1]['physical']
        and p1_e1[1]['usage']['total_tokens'] == 100
        and st_p.task_view('p1')['node_status']['e1'] == FAILED
        and obs_p1.count('D1_e_empty') == 2)

    # 4. downstream never consumes stale inputs: e1-fault task — fb (new
    #    call) changes facts ⇒ r_fbd executes as a NEW call (input
    #    identity changed — NOT a cache hit). v_fbd correctly does NOT
    #    fire here: the scripted r answer text is identical, so the
    #    production final-state rule says r unchanged (parity-verified by
    #    the LOCAL arm pass above).
    t1_calls = [(c['node'], c['kind'], c['cached'])
                for c in run_mine('cascade', 'LOCAL', make_tasks())['events']
                if c['event'] == 'call' and c['task'] == 'm1t1']
    checks['b4_cascade_no_stale_reuse'] = (
        ('e1', 'plain', False) in t1_calls
        and ('e1', 'fb', False) in t1_calls
        and ('r', 'fbd', False) in t1_calls)

    # 5. RUNNING nodes never appear in recovery jobs (serial engine keeps
    #    call_start/call strictly alternating; M3 judge rejects R/π on them)
    run5 = run_mine('running_probe', 'FULL', make_tasks())
    ok_alt = True
    depth = 0
    for e in run5['events']:
        if e['event'] == 'call_start':
            depth += 1
            ok_alt &= depth == 1
        elif e['event'] == 'call':
            depth -= 1
            ok_alt &= depth == 0
    checks['b5_no_midflight_rewrite'] = ok_alt

    # 6. cold start & switch costs counted exactly once
    ev6 = run_mine('switch_once', 'FULL', make_tasks())['events']
    sw = [e for e in ev6 if e['event'] == 'switch']
    sess6 = next(e for e in ev6 if e['event'] == 'session_summary')
    checks['b6_switch_once'] = (
        len(sw) == len({e['idx'] for e in sw})
        and len(sw) == len(sess6['switch_indices']))

    # 7. E2E spans release → termination incl. recovery calls
    st7 = run_mine('e2e_probe', 'FULL', make_tasks())['state']
    tv = st7.task_view('m1t1')  # e1-fault task — replayed
    checks['b7_e2e_release_to_completion'] = (
        tv['completion_time'] is not None
        and tv['e2e_s'] == round(tv['completion_time']
                                 - tv['release_time'], 6)
        and tv['calls'] > 4)

    # 8. determinism + zero-call sentinel
    a = (RUNS_DIR / 'det_a' / 'TASK_LEDGER.jsonl')
    b = (RUNS_DIR / 'det_b' / 'TASK_LEDGER.jsonl')
    run_mine('det_a', 'FULL', make_tasks())
    run_mine('det_b', 'FULL', make_tasks())
    checks['b8_determinism'] = a.read_bytes() == b.read_bytes()
    calls_full = None
    run8 = run_mine('z1_probe', 'FULL', make_tasks())
    calls_full = sum(1 for e in run8['events'] if e['event'] == 'call')
    physical_full = sum(1 for e in run8['events'] if e['event'] == 'call'
                        and e['physical'])
    checks['b8_z1_sentinel'] = (run8['server'].invocations
                                == physical_full)

    all_pass = all(checks.values())
    evidence = dict(milestone='M4', checks=checks, all_pass=all_pass,
                    zero_model_calls=True, detail=detail)
    (HERE / 'evidence' / 'M4_EVIDENCE.json').write_text(
        json.dumps(evidence, indent=1, ensure_ascii=False))
    for k, v in checks.items():
        print(f'  {k}: {"PASS" if v else "FAIL"}')
    print(f'\n{sum(checks.values())}/{len(checks)} checks; '
          f'zero_model_calls=true; '
          f'{"ALL PASS" if all_pass else "FAIL PRESENT"}')
    return 0 if all_pass else 2


if __name__ == '__main__':
    with no_socket():
        raise SystemExit(main())
